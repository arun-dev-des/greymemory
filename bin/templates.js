export function generateConfig(answers) {
  const {
    extractorProvider,
    extractorModel,
    embedderProvider,
    embedderModel,
    dir,
    container,
    existingDbPath = null
  } = answers

  function buildDbConnection(existingDbPath) {
    if (!existingDbPath) return null
    return `import Database from 'better-sqlite3'

const db = new Database('${existingDbPath}')`
  }

  const extractor    = buildExtractor(extractorProvider, extractorModel)
  const embedder     = buildEmbedder(embedderProvider, embedderModel)
  const imports      = buildImports(extractorProvider, embedderProvider, existingDbPath)
  const dbConnection = buildDbConnection(existingDbPath)

  const greyMemoryOptions = existingDbPath
    ? `  extractor,\n  embedder,\n  db,\n  container: '${container}'`
    : `  extractor,\n  embedder,\n  dir: '${dir}',\n  container: '${container}'`

  return `// greymemory.config.js — generated by greymemory init
// safe to commit — no API keys here, keys live in .env
import 'dotenv/config'
import GreyMemory from 'greymemory'
${imports}

${dbConnection ? dbConnection + '\n' : ''}
${extractor}

${embedder}

export default new GreyMemory({
${greyMemoryOptions}

  // optional — tell greymemory what to index and who this memory belongs to
  // filterPrompt:  'Index: decisions, preferences, goals. Skip: small talk, greetings.',
  // entityContext: 'Memory for <name>, <role>. Focus on: <topics>.',
})
`
}

function buildImports(extractorProvider, embedderProvider, existingDbPath = null) {
  const imports = []
  if (extractorProvider === 'Anthropic') imports.push("import Anthropic from '@anthropic-ai/sdk'")
  if (extractorProvider === 'OpenAI')    imports.push("import OpenAI from 'openai'")
  if (embedderProvider  === 'Cohere')    imports.push("import { CohereClient } from 'cohere-ai'")
  // better-sqlite3 is already a greymemory dependency — no install needed
  return imports.join('\n')
}

// v0.3 — extractor receives a ready-made prompt string from greymemory
// it just wires it to the LLM and returns the raw response string
// greymemory handles prompt building, JSON parsing, and validation internally
function buildExtractor(provider, model) {
  if (provider === 'Anthropic') {
    return `const anthropic = new Anthropic({ apiKey: process.env.ANTHROPIC_API_KEY })
 
const extractor = async (prompt) => {
  const res = await anthropic.messages.create({
    model: '${model}',
    max_tokens: 1024,
    messages: [{ role: 'user', content: prompt }]
  })
  return res.content[0].text.trim()
}`
  }
 
  if (provider === 'OpenAI') {
    return `const openai = new OpenAI({ apiKey: process.env.OPENAI_API_KEY })
 
const extractor = async (prompt) => {
  const res = await openai.chat.completions.create({
    model: '${model}',
    messages: [{ role: 'user', content: prompt }]
  })
  return res.choices[0].message.content.trim()
}`
  }
 
  if (provider === 'Ollama') {
    return `const extractor = async (prompt) => {
  const res = await fetch('http://localhost:11434/api/chat', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      model: '${model}',
      stream: false,
      messages: [{ role: 'user', content: prompt }]
    })
  })
  const data = await res.json()
  return data.message.content.trim()
}`
  }
}

function buildEmbedder(provider, model) {
  if (provider === 'Ollama') {
    return `const embedder = async (text) => {
  const res = await fetch('http://localhost:11434/api/embeddings', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      model: '${model}',
      prompt: text
    })
  })
  const data = await res.json()
  return data.embedding
}`
  }

  if (provider === 'OpenAI') {
    return `const openaiEmbedder = new OpenAI({ apiKey: process.env.OPENAI_API_KEY })

const embedder = async (text) => {
  const res = await openaiEmbedder.embeddings.create({
    model: '${model}',
    input: text
  })
  return res.data[0].embedding
}`
  }

  if (provider === 'Cohere') {
    return `const cohere = new CohereClient({ token: process.env.COHERE_API_KEY })

const embedder = async (text) => {
  const res = await cohere.embed({
    texts: [text],
    model: '${model}',
    inputType: 'search_document'
  })
  return res.embeddings[0]
}`
  }
}