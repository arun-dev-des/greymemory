export function generateConfig(answers) {
  const {
    extractorProvider,
    extractorModel,
    extractorKey,
    embedderProvider,
    embedderModel,
    embedderKey,
    dir,
    container
  } = answers

  const extractor = buildExtractor(extractorProvider, extractorModel, extractorKey)
  const embedder  = buildEmbedder(embedderProvider, embedderModel, embedderKey)
  const imports   = buildImports(extractorProvider, embedderProvider)

  return `// greymemory.config.js — generated by greymemory init
import GreyMemory from 'greymemory'
${imports}

${extractor}

${embedder}

export default new GreyMemory({
  extractor,
  embedder,
  dir: '${dir}',
  container: '${container}'
})
`
}

function buildImports(extractorProvider, embedderProvider) {
  const imports = []
  if (extractorProvider === 'Anthropic') imports.push("import Anthropic from '@anthropic-ai/sdk'")
  if (extractorProvider === 'OpenAI')    imports.push("import OpenAI from 'openai'")
  if (embedderProvider  === 'Cohere')    imports.push("import { CohereClient } from 'cohere-ai'")
  return imports.join('\n')
}

function buildExtractor(provider, model, key) {
  // strip description text — keep only model name
  const modelName = model.split(' ')[0]

  if (provider === 'Anthropic') {
    return `const anthropic = new Anthropic({ apiKey: '${key}' })

const extractor = async (messages) => {
  const res = await anthropic.messages.create({
    model: '${modelName}',
    max_tokens: 1000,
    messages: [{
      role: 'user',
      content: \`Extract facts from this conversation as a flat JSON object.
Rules:
- keys are short snake_case strings
- values are strings only
- no nested objects, no arrays
- only factual information about the user
- respond with JSON only, no explanation

Conversation:
\${JSON.stringify(messages)}\`
    }]
  })
  const text = res.content[0].text.trim()
  return JSON.parse(text.replace(/\`\`\`json|\`\`\`/g, '').trim())
}`
  }

  if (provider === 'OpenAI') {
    return `const openai = new OpenAI({ apiKey: '${key}' })

const extractor = async (messages) => {
  const res = await openai.chat.completions.create({
    model: '${modelName}',
    messages: [{
      role: 'user',
      content: \`Extract facts from this conversation as a flat JSON object.
Rules:
- keys are short snake_case strings
- values are strings only
- no nested objects, no arrays
- only factual information about the user
- respond with JSON only, no explanation

Conversation:
\${JSON.stringify(messages)}\`
    }]
  })
  const text = res.choices[0].message.content.trim()
  return JSON.parse(text.replace(/\`\`\`json|\`\`\`/g, '').trim())
}`
  }

  if (provider === 'Ollama') {
    return `const extractor = async (messages) => {
  const res = await fetch('http://localhost:11434/api/chat', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      model: '${modelName}',
      stream: false,
      messages: [{
        role: 'user',
        content: \`Extract facts from this conversation as a flat JSON object.
Rules:
- keys are short snake_case strings
- values are strings only
- no nested objects, no arrays
- only factual information about the user
- respond with JSON only, no explanation

Conversation:
\${JSON.stringify(messages)}\`
      }]
    })
  })
  const data = await res.json()
  const text = data.message.content.trim()
  return JSON.parse(text.replace(/\`\`\`json|\`\`\`/g, '').trim())
}`
  }
}

function buildEmbedder(provider, model, key) {
  const modelName = model.split(' ')[0]

  if (provider === 'Ollama') {
    return `const embedder = async (text) => {
  const res = await fetch('http://localhost:11434/api/embeddings', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      model: '${modelName}',
      prompt: text
    })
  })
  const data = await res.json()
  return data.embedding
}`
  }

  if (provider === 'OpenAI') {
    return `const openaiEmbedder = new OpenAI({ apiKey: '${key}' })

const embedder = async (text) => {
  const res = await openaiEmbedder.embeddings.create({
    model: '${modelName}',
    input: text
  })
  return res.data[0].embedding
}`
  }

  if (provider === 'Cohere') {
    return `const cohere = new CohereClient({ token: '${key}' })

const embedder = async (text) => {
  const res = await cohere.embed({
    texts: [text],
    model: '${modelName}',
    inputType: 'search_document'
  })
  return res.embeddings[0]
}`
  }
}