// export-hero-graph.mjs
//
// Generates the static hero-graph dataset for the story page.
// Reads the bench-v15 DB (container 031748ae), keeps the relationship-rich
// core of the graph, and writes a slim JSON payload to
// client/src/story/data/hero-graph.json.
//
// Usage: node server/scripts/export-hero-graph.mjs [db-path]

import path from 'path'
import fs from 'fs'
import { fileURLToPath } from 'url'
import Database from 'better-sqlite3'
import { buildGraph } from '../viz/graph.js'

const __dirname = path.dirname(fileURLToPath(import.meta.url))

const DEFAULT_DB = '/Users/ma2072/Documents/greymemory/benchmark/.greymemory-bench-v15/greymemory.db'
const CONTAINER = '031748ae'
const MAX_NODES = 120

const dbPath = path.resolve(process.argv[2] ?? DEFAULT_DB)
const outPath = path.resolve(__dirname, '../../client/src/story/data/hero-graph.json')

if (!fs.existsSync(dbPath)) {
  console.error(`DB not found: ${dbPath}`)
  process.exit(1)
}

const db = new Database(dbPath, { readonly: true })
const { nodes, links } = buildGraph(db, CONTAINER, { includeChunks: false })
db.close()

console.log(`buildGraph: ${nodes.length} nodes, ${links.length} links (container ${CONTAINER})`)

// 1. Keep every node that participates in an UPDATES/EXTENDS/DERIVES link.
const relLinks = links.filter(l => ['UPDATES', 'EXTENDS', 'DERIVES'].includes(l.relation))
const keep = new Set()
for (const l of relLinks) {
  keep.add(l.source)
  keep.add(l.target)
}

// 2. Top up to MAX_NODES with is_latest singleton facts, in stable memoryId order.
const singletons = nodes
  .filter(n => !keep.has(n.id) && n.is_latest)
  .sort((a, b) => a.memoryId - b.memoryId)
for (const n of singletons) {
  if (keep.size >= MAX_NODES) break
  keep.add(n.id)
}

// 3. Slim nodes; drop links with a missing endpoint. `value` is kept
// (truncated) so the hero graph can show the real memory text on hover.
const outNodes = nodes
  .filter(n => keep.has(n.id))
  .map(n => ({
    id: n.id,
    type: n.type,
    label: n.label,
    value: (n.value ?? '').slice(0, 120),
    memory_type: n.memory_type,
    is_latest: n.is_latest,
    is_expired: Boolean(n.is_expired),
  }))

const outLinks = relLinks
  .filter(l => keep.has(l.source) && keep.has(l.target))
  .map(l => ({ source: l.source, target: l.target, relation: l.relation }))

const payload = {
  _source: 'bench-v15/031748ae',
  _note: 'generated by server/scripts/export-hero-graph.mjs — do not hand-edit',
  nodes: outNodes,
  links: outLinks,
}

fs.mkdirSync(path.dirname(outPath), { recursive: true })
const json = JSON.stringify(payload, null, 2)
fs.writeFileSync(outPath, json + '\n')

console.log(`wrote ${outPath}`)
console.log(`nodes: ${outNodes.length}, links: ${outLinks.length}, size: ${(json.length / 1024).toFixed(1)} KB`)
